param(
    [Parameter(Mandatory = $true)]
    [string]$PackDir,

    [Parameter(Mandatory = $true)]
    [string]$Version,

    [Parameter(Mandatory = $true)]
    [string]$BaseUrl,

    [string]$OutputDir = ".\dist",
    [string]$GameVersion = "3.4",
    [string]$PrivateKeyXml = "",
    [string]$Remove = ""
)

$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.IO.Compression.FileSystem

function Get-ModInfoValue {
    param($Xml, [string]$Name, [string]$Fallback)

    $node = $Xml.SelectSingleNode("/xml/$Name")
    if ($null -eq $node) {
        $node = $Xml.SelectSingleNode("/xml/ModInfo/$Name")
    }

    if ($null -eq $node) {
        return $Fallback
    }

    $value = $node.GetAttribute("value")
    if ([string]::IsNullOrWhiteSpace($value)) {
        return $Fallback
    }

    return $value.Trim()
}

function ConvertTo-SafeFolder {
    param([string]$Name)

    $safe = [regex]::Replace($Name, '[^0-9A-Za-z_\-]', '_')
    if ([string]::IsNullOrWhiteSpace($safe)) {
        throw "Could not derive a safe folder name from '$Name'."
    }

    return $safe
}

if ($Version -notmatch '^[0-9A-Za-z._\-]+$' -or $Version -eq '.' -or $Version -eq '..' -or $Version.Contains('..')) {
    throw "Version '$Version' contains characters that are not safe for a release path."
}

$PackDir = (Resolve-Path $PackDir).Path
if ([IO.Path]::IsPathRooted($OutputDir)) {
    $OutputDir = [IO.Path]::GetFullPath($OutputDir)
}
else {
    $OutputDir = [IO.Path]::GetFullPath((Join-Path (Get-Location).Path $OutputDir))
}
$BaseUrl = $BaseUrl.TrimEnd('/')

New-Item -ItemType Directory -Force $OutputDir | Out-Null

$mods = @()
$modDirs = Get-ChildItem -Path $PackDir -Directory | Sort-Object Name

foreach ($dir in $modDirs) {
    if ($dir.Name -eq '000_QLNPackBootstrap' -or $dir.Name -eq 'Data') {
        Write-Host "Skipping $($dir.Name): bootstrap files are not part of the pack."
        continue
    }

    $modInfoPath = Join-Path $dir.FullName 'ModInfo.xml'
    $hasModInfo = Test-Path $modInfoPath

    if ($hasModInfo) {
        [xml]$info = Get-Content -Path $modInfoPath -Raw
        $name = Get-ModInfoValue -Xml $info -Name 'Name' -Fallback $dir.Name
        $modVersion = Get-ModInfoValue -Xml $info -Name 'Version' -Fallback '0.0.0'
        $displayName = Get-ModInfoValue -Xml $info -Name 'DisplayName' -Fallback $name

        if ($name -notmatch '^[0-9A-Za-z_\-]+$') {
            Write-Warning "ModInfo.xml in $($dir.Name) has an invalid Name '$name'. Using a safe folder name instead."
            $name = ConvertTo-SafeFolder $dir.Name
            $displayName = $dir.Name
            $hasModInfo = $false
        }
    }
    else {
        $name = ConvertTo-SafeFolder $dir.Name
        $modVersion = '0.0.0'
        $displayName = $dir.Name
    }

    $installFolder = ConvertTo-SafeFolder $dir.Name
    if ($installFolder -eq '000_QLNPackBootstrap' -or $installFolder -eq 'Data') {
        throw "Mod folder '$($dir.Name)' uses a reserved name."
    }

    $zipName = (ConvertTo-SafeFolder ($dir.Name + '-' + $modVersion)) + '.zip'
    $zipPath = Join-Path $OutputDir $zipName

    if (Test-Path $zipPath) {
        Remove-Item $zipPath -Force
    }

    [System.IO.Compression.ZipFile]::CreateFromDirectory(
        $dir.FullName,
        $zipPath,
        [System.IO.Compression.CompressionLevel]::Optimal,
        $false)

    $hash = (Get-FileHash -Path $zipPath -Algorithm SHA256).Hash.ToLowerInvariant()
    $size = (Get-Item $zipPath).Length

    $mods += [ordered]@{
        name = $name
        displayName = $displayName
        version = $modVersion
        url = "$BaseUrl/$zipName"
        sha256 = $hash
        size = $size
        target = "client"
        installFolder = $installFolder
        required = $true
    }

    if ($hasModInfo) {
        Write-Host ("Packed {0} v{1} -> {2} ({3} bytes)" -f $displayName, $modVersion, $zipName, $size)
    }
    else {
        Write-Host ("Packed {0} (no ModInfo.xml) v{1} -> {2} ({3} bytes)" -f $displayName, $modVersion, $zipName, $size)
    }
}

if ($mods.Count -eq 0) {
    throw "No mod folders were found in $PackDir."
}

$removeList = @()
if (-not [string]::IsNullOrWhiteSpace($Remove)) {
    $removeList = @($Remove.Split(',') | ForEach-Object { $_.Trim() } | Where-Object { $_.Length -gt 0 })
    foreach ($folder in $removeList) {
        if ($folder -notmatch '^[0-9A-Za-z_\-]+$' -or $folder -eq '000_QLNPackBootstrap' -or $folder -eq 'Data') {
            throw "Remove entry '$folder' is not a safe pack folder."
        }
    }
}

$manifest = [ordered]@{
    schemaVersion = 1
    packVersion = $Version
    gameVersion = $GameVersion
    generatedAt = (Get-Date).ToUniversalTime().ToString("o")
    notes = "Generated by pack-release.ps1"
    mods = @($mods)
    remove = @($removeList)
}

$json = $manifest | ConvertTo-Json -Depth 8
$manifestPath = Join-Path $OutputDir 'manifest.json'
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$manifestBytes = $utf8NoBom.GetBytes($json)
[IO.File]::WriteAllBytes($manifestPath, $manifestBytes)

Write-Host ""
Write-Host "Manifest: $manifestPath"

if (-not [string]::IsNullOrWhiteSpace($PrivateKeyXml)) {
    $privateXml = [IO.File]::ReadAllText((Resolve-Path $PrivateKeyXml).Path)
    $rsa = New-Object System.Security.Cryptography.RSACryptoServiceProvider
    try {
        $rsa.PersistKeyInCsp = $false
        $rsa.FromXmlString($privateXml)

        $signature = $rsa.SignData(
            $manifestBytes,
            [System.Security.Cryptography.HashAlgorithmName]::SHA256,
            [System.Security.Cryptography.RSASignaturePadding]::Pkcs1)

        $signaturePath = Join-Path $OutputDir 'manifest.json.sig'
        [IO.File]::WriteAllText($signaturePath, [Convert]::ToBase64String($signature))
        Write-Host "Signature: $signaturePath"
    }
    finally {
        $rsa.Dispose()
    }
}
else {
    Write-Host ""
    Write-Host "WARNING: no PrivateKeyXml supplied. The manifest is unsigned."
    Write-Host "The bootstrap will show an unsigned-manifest warning to players."
}

Write-Host ""
Write-Host "Upload the contents of $OutputDir to a GitHub release, then point"
Write-Host "ManifestUrl at: $BaseUrl/manifest.json"
